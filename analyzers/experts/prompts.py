EXPERT_PROMPTS = {
    'stocks':   _STOCKS,
    'economy':  _ECONOMY,
    'tech':     _TECH,
    'politics': _POLITICS,
    'world':    _WORLD,
    'society':  _SOCIETY,
    'sports':   _SPORTS,
    'culture':  _CULTURE,
    'general':  _GENERAL,
}


def build_expert_system(base_system, expert_id, feedback_cache=''):
    """베이스 시스템 프롬프트에 전문가 특화 섹션 + 피드백을 합친다."""
    expert_section = EXPERT_PROMPTS.get(expert_id) or EXPERT_PROMPTS['general']
    parts = [base_system, expert_section]
    if feedback_cache:
        parts.append(feedback_cache)
    return '\n\n'.join(parts)
